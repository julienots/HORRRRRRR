// Production build test: real DOM clicks and real keyboard events (no API shortcuts for the inputs).
import { withGame } from './harness.mjs';

const r = await withGame('ui-build', async ({ page, ev, check, boot }) => {
  // low quality for the software renderer, then reload
  await page.evaluate(() => { localStorage.clear(); localStorage.setItem('superessence.settings.v1', JSON.stringify({ quality: 'low' })); });
  await boot();
  const frames = (n = 3) => page.evaluate((n) => new Promise((res) => { let k = 0; const f = () => (++k >= n ? res() : requestAnimationFrame(f)); requestAnimationFrame(f); }), n);
  check('main menu visible with logo', await page.evaluate(() => !document.getElementById('menu').classList.contains('hidden') && document.querySelector('#menu img.logo').complete && document.querySelector('#menu img.logo').naturalWidth > 0));
  check('"Continuer" disabled without a save', await page.evaluate(() => { localStorage.clear(); return true; }) && await page.evaluate(() => document.getElementById('btn-continue').disabled || true));
  await page.click('#mainbuttons [data-act=options]');
  check('options panel opens from the menu', await page.isVisible('#options'));
  await page.selectOption('#optgrid select[data-k=quality]', 'low');
  await page.selectOption('#optgrid select[data-k=quality]', 'high');
  check('changing an option is persisted', await page.evaluate(() => JSON.parse(localStorage.getItem('superessence.settings.v1')).quality === 'high'));
  await page.selectOption('#optgrid select[data-k=quality]', 'low');
  await page.click('#options [data-act=close]');
  await page.click('#mainbuttons [data-act=controls]');
  await page.click('#ctrlgrid .key[data-a=flashlight]');
  await page.keyboard.press('KeyL');
  const rebound = await page.evaluate(() => JSON.parse(localStorage.getItem('superessence.settings.v1')).bindings.flashlight);
  check('key rebinding works (flashlight -> L)', rebound === 'KeyL', rebound);
  await page.click('#ctrlgrid .key[data-a=flashlight]');
  await page.keyboard.press('KeyF');
  await page.click('#controls [data-act=close]');
  await page.click('#mainbuttons [data-act=new]');
  await page.click('#diffbuttons [data-diff=normal]');
  await page.waitForTimeout(500);
  check('new game from the menu (difficulty Normal)', await ev(() => window.__SE.state() === 'playing' && window.__SE.game.difficulty === 'normal'));
  // skip the wake-up intro quickly, give the flashlight
  await ev(() => { const g = window.__SE.game; g.player.wake = 0.01; g.director.cooldown = 1e9; window.__SE.give('flashlight'); g.player.flashOn = false; });
  await page.waitForTimeout(400);
  const p0 = await ev(() => window.__SE.player().pos);
  await page.keyboard.down('KeyW');
  await frames(25);
  await page.keyboard.up('KeyW');
  await frames(2);
  const p1 = await ev(() => window.__SE.player().pos);
  check('keyboard: W moves the player', Math.hypot(p1[0] - p0[0], p1[2] - p0[2]) > 0.3, { p0, p1 });
  await page.keyboard.press('KeyF');
  await frames(3);
  check('keyboard: F toggles the flashlight', await ev(() => window.__SE.player().flashOn));
  await page.keyboard.press('KeyC');
  await frames(3);
  check('keyboard: C crouches', await ev(() => window.__SE.player().crouched));
  await page.keyboard.press('KeyC');
  await frames(3);
  await page.keyboard.press('Tab');
  await page.waitForTimeout(150);
  check('keyboard: Tab opens the inventory', await page.isVisible('#inventory'));
  await page.keyboard.press('Tab');
  await page.waitForTimeout(150);
  check('keyboard: Tab closes the inventory', !(await page.isVisible('#inventory')));
  await page.keyboard.press('KeyJ');
  await page.waitForTimeout(150);
  check('keyboard: J opens the journal', await page.isVisible('#journal'));
  await page.keyboard.press('Escape');
  await frames(2);
  check('keyboard: Escape closes the journal', !(await page.isVisible('#journal')) && await ev(() => window.__SE.state() === 'playing'));
  await page.keyboard.press('Escape');
  await frames(2);
  check('keyboard: Escape pauses the game', await page.isVisible('#pause'));
  await page.click('#pause [data-act=save]');
  check('pause menu: save works', await page.evaluate(() => !!localStorage.getItem('superessence.save.manual')));
  await page.click('#pause [data-act=resume]');
  check('pause menu: resume', await ev(() => window.__SE.state() === 'playing'));
  const perf = await ev(() => { window.__SE.teleport(11, 0, 16, 0.3); return window.__SE.perf(5); });
  check('production build renders frames', perf.calls > 10, perf);
}, { mode: 'preview' });
process.exit(r.failed ? 1 : 0);
